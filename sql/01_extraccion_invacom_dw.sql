-- Extracción de solo lectura desde el esquema estrella INVACOM_DW.
SELECT F.ID_FACT_VENTA, F.ORDERID_ORIGEN AS ID_PEDIDO,
 F.ID_PRODUCTO, F.ID_CLIENTE, TO_CHAR(T.FECHA_COMPLETA,'YYYY-MM-DD') AS FECHA_PEDIDO,
 T.ANIO, T.MES, P.NOMBRE_PRODUCTO AS PRODUCTO, P.NOMBRE_CATEGORIA AS CATEGORIA,
 C.NOMBRE_CLIENTE AS CLIENTE, C.CIUDAD AS CIUDAD_CLIENTE, C.PAIS AS PAIS_CLIENTE,
 F.CANTIDAD_VENDIDA, F.IMPORTE_BRUTO, F.IMPORTE_DESCUENTO, F.IMPORTE_NETO
FROM INVACOM_DW.FACT_VENTAS F
JOIN INVACOM_DW.DIM_TIEMPO T ON T.ID_FECHA=F.ID_FECHA
JOIN INVACOM_DW.DIM_PRODUCTO P ON P.ID_PRODUCTO=F.ID_PRODUCTO
JOIN INVACOM_DW.DIM_CLIENTE C ON C.ID_CLIENTE=F.ID_CLIENTE
ORDER BY F.ORDERID_ORIGEN,F.ID_PRODUCTO;
